// GenerateRandomName returns a realistic Russian full name for anonymous call join.
func GenerateRandomName() string {
	isMale := rand.Intn(2) == 0
	if isMale {
		first := maleFirstNames[rand.Intn(len(maleFirstNames))]
		last := lastNames[rand.Intn(len(lastNames))]
		return fmt.Sprintf("%s %s", first, last)
	}
	first := femaleFirstNames[rand.Intn(len(femaleFirstNames))]
	last := lastNames[rand.Intn(len(lastNames))] + "а"
	return fmt.Sprintf("%s %s", first, last)
}
